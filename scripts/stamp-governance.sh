#!/bin/sh
# Stamp a governance file with a content hash of its governance block.
#
#   sh scripts/stamp-governance.sh <file> <marker-slug>
#
# The hash lets any point-in-time copy of a governance file (in a Power BI project, or in a
# standalone custom visual repo) detect whether it is behind this pack's canonical version,
# without needing network access — the freshness checks in power-bi-dev §5 and
# power-bi-visual-dev §7 compare hashes against this repo on the same machine.
#
# Two governance files, two independent marker slugs:
#   CLAUDE.md              power-bi-skills          (report projects; copied to pbi-starter/CLAUDE.md)
#   pbiviz-starter/CLAUDE.md  power-bi-visual-skills (standalone .pbiviz repos; canonical in place)
#
# Called by scripts/git-hooks/pre-commit. Idempotent: stamping an unchanged block twice yields
# the same hash, so it never creates a spurious diff. Prints the hash on success.

set -e

FILE="$1"
SLUG="$2"

# shellcheck disable=SC2015  # the usage block must run when either test fails, which is what && || does here
[ -n "$FILE" ] && [ -n "$SLUG" ] || { echo "usage: stamp-governance.sh <file> <marker-slug>" >&2; exit 2; }
[ -f "$FILE" ] || { echo "stamp-governance: no such file: $FILE" >&2; exit 1; }

BEGIN_MARKER="<!-- BEGIN ${SLUG} -->"
END_MARKER="<!-- END ${SLUG} -->"
HASH_PREFIX="<!-- ${SLUG}-hash:"

grep -qF "$BEGIN_MARKER" "$FILE" || { echo "stamp-governance: $FILE has no '$BEGIN_MARKER'" >&2; exit 1; }
grep -qF "$END_MARKER"   "$FILE" || { echo "stamp-governance: $FILE has no '$END_MARKER'" >&2; exit 1; }

# Hash the block strictly between the markers, excluding the hash line itself (else the hash
# would depend on its own previous value) and normalizing CRLF (else a line-ending flip alone
# would read as a governance change).
NEW_HASH=$(awk -v b="$BEGIN_MARKER" -v e="$END_MARKER" -v p="$HASH_PREFIX" '
    $0 == b { inside = 1; next }
    $0 == e { inside = 0 }
    inside && index($0, p) != 1 { print }
' "$FILE" | tr -d '\r' | sha256sum | cut -c1-12)

# Drop any previous hash line, then re-insert it immediately after the BEGIN marker.
grep -v "^${HASH_PREFIX}" "$FILE" > "${FILE}.tmp"
awk -v hash="$NEW_HASH" -v b="$BEGIN_MARKER" -v slug="$SLUG" '
    { print }
    $0 == b { print "<!-- " slug "-hash: " hash " (auto-generated by pre-commit hook; do not hand-edit) -->" }
' "${FILE}.tmp" > "$FILE"
rm -f "${FILE}.tmp"

echo "$NEW_HASH"
